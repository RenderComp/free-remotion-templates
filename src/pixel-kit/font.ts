export function glyphFor(ch: string): Glyph {
  return G[ch] ?? G[ch.toUpperCase()] ?? G["-"];
}

// Does the font have a real glyph for this char (vs. the "-" fallback)?
export function hasGlyph(ch: string): boolean {
  return ch in G || ch.toUpperCase() in G;
}

export type Cell = { x: number; y: number };

/** Expand a string into lit cell coords. Glyphs are spaced 1 col apart; space = GLYPH_W. */
export function layoutText(text: string): { cells: Cell[]; cols: number } {
  const cells: Cell[] = [];
  let cursor = 0;
  for (const ch of text) {
    const g = glyphFor(ch);
    for (let r = 0; r < GLYPH_H; r++) {
      const row = g[r] ?? "00000";
      for (let c = 0; c < GLYPH_W; c++) {
        if (row[c] === "1") cells.push({ x: cursor + c, y: r });
      }
    }
    cursor += GLYPH_W + 1;
  }
  return { cells, cols: Math.max(0, cursor - 1) };
}

/** Width in cells of a string (for centering / alignment). */
export function measureText(text: string): number {
  return text.length === 0 ? 0 : text.length * (GLYPH_W + 1) - 1;
}
